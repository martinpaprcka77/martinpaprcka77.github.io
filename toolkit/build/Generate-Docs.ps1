<#
.SYNOPSIS
    Regenerates docs/20-reference.md from the Toolkit module (single source of truth).
.DESCRIPTION
    Reads the built/loaded manifest for the exported-function list, groups the
    functions by concern, and counts the Pester suite. Everything the other docs
    need (function inventory, counts) is generated here so README/AGENTS no longer
    restate numbers that drift.

    Diagnostics are local-only by design: no function in the Diagnostics group
    performs network I/O. The generated reference states this invariant explicitly.
.EXAMPLE
    pwsh -File build/Generate-Docs.ps1
.NOTES
    Run from the repo root or anywhere (paths are derived from $PSScriptRoot).
#>
[CmdletBinding()]
param(
    [string]$OutputPath = (Join-Path (Split-Path $PSScriptRoot -Parent) 'docs' '20-reference.md')
)

$ErrorActionPreference = 'Stop'

$root       = Split-Path $PSScriptRoot -Parent
$manifest   = Join-Path $root 'Toolkit' 'Toolkit.psd1'
$testsPath  = Join-Path $root 'tests' 'Toolkit.Tests.ps1'

if (-not (Test-Path -LiteralPath $manifest)) { throw "Manifest not found: $manifest" }

$module = Import-Module $manifest -Force -PassThru
$version = (Test-ModuleManifest $manifest).Version.ToString()
$exported = $module.ExportedFunctions.Keys | Sort-Object

# Concern groups (keep in sync with the module's folder split when scaffolded).
$groups = [ordered]@{
    'Menu'          = @('Start-MainMenu','Show-Menu','Show-DotfilesMenu','Show-GitMenu','Show-PwshMenu','Show-TerminalMenu','Show-VSCodeMenu')
    'Console / Logging' = @('Write-Info','Write-Success','Write-Warn','Write-Err','Confirm-Action')
    'Diagnostics'   = @('Invoke-SystemCheck','Get-SystemSummary','Get-ShellInfo','Get-DiskStatus','Get-ServiceStatus','Get-NetworkInfo','Get-TopProcesses','Get-ModuleStackStatus','Get-ModulePathStatus','Test-LegacyPowerShellGetPresent','Test-PSResourceGetReady')
    'Connectivity'  = @('Test-NetworkEndpoint')  # the one network-touching function
    'Configuration' = @('Get-ToolkitConfig','Save-ToolkitConfig','Merge-Hashtable')
    'ModulePath'    = @('Get-PSModulePath','Add-PSModulePath','Remove-PSModulePath','Reset-PSModulePath','Export-PSModulePath','Import-PSModulePath','Test-PSModulePath')
}

$categorised = [System.Collections.Generic.HashSet[string]]::new()
foreach ($names in $groups.Values) { foreach ($n in $names) { $null = $categorised.Add($n) } }
$uncategorised = @($exported | Where-Object { -not $categorised.Contains($_) })

$testCount = 'n/a'
if ((Test-Path -LiteralPath $testsPath) -and (Get-Module -ListAvailable Pester)) {
    try {
        $run = Invoke-Pester -Path $testsPath -Output None -PassThru
        $testCount = "$($run.TotalCount) ($($run.PassedCount) pass / $($run.FailedCount) fail)"
    } catch {
        Write-Warning "Could not run Pester: $_"
    }
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Toolkit — API reference')
$lines.Add('')
$lines.Add('> Generated by `build/Generate-Docs.ps1`. **Do not edit by hand.** Run the generator after changing exports.')
$lines.Add('')
$lines.Add("| Fact | Value |")
$lines.Add('|------|-------|')
$lines.Add("| Module | ``Toolkit`` |")
$lines.Add("| Version | $version |")
$lines.Add("| Exported functions | $($exported.Count) |")
$lines.Add("| Pester tests | $testCount |")
$lines.Add('')
$lines.Add('**Invariants**')
$lines.Add('')
$lines.Add('- **Diagnostics are local-only** — nothing in the Diagnostics group performs network I/O (the only network-touching function, `Test-NetworkEndpoint`, is grouped under Connectivity).')
$lines.Add('- **Logging is centralised** — modules and ops scripts emit through the `Write-*` family; no ad-hoc `Write-Host` formatting helpers are duplicated per script.')
$lines.Add('')
$lines.Add('## Functions by concern')
$lines.Add('')

foreach ($group in $groups.Keys) {
    $names = @($groups[$group] | Where-Object { $exported -contains $_ })
    $lines.Add("### $group ($($names.Count))")
    $lines.Add('')
    $lines.Add('| Function |')
    $lines.Add('|----------|')
    foreach ($n in $names) { $lines.Add("| ``$n`` |") }
    $lines.Add('')
}

if ($uncategorised.Count) {
    $lines.Add("### Uncategorised ($($uncategorised.Count))")
    $lines.Add('')
    foreach ($n in $uncategorised) { $lines.Add("- ``$n``") }
    $lines.Add('')
}

[System.IO.File]::WriteAllLines($OutputPath, $lines)
Write-Host "Wrote $OutputPath ($($exported.Count) functions)"
